import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'

const projectRoot = join(process.cwd(), '..')
const runtimeRoot = join(projectRoot, 'runtime_store', 'v13')
const outDir = join(process.cwd(), 'src', 'generated')
const publicGeneratedDir = join(process.cwd(), 'public', 'generated')
const tsOutFile = join(outDir, 'v13Runtime.generated.ts')
const jsonOutFile = join(publicGeneratedDir, 'v13Runtime.generated.json')

function readUtf8(file) {
  return readFileSync(file, 'utf8').replace(/^\uFEFF/, '')
}

function readJson(file, fallback = null) {
  if (!existsSync(file)) return fallback
  return JSON.parse(readUtf8(file))
}

function readJsonl(file) {
  if (!existsSync(file)) return []
  return readUtf8(file)
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter(Boolean)
    .map((line) => JSON.parse(line))
}

function buildPayload() {
  const manifest = readJson(join(runtimeRoot, 'v13_manifest.json'), {
    runtime_id: 'fame-v13-theory-runtime',
    version: '13.0.0',
    project_id: 'fame-agent-gateway',
    memory_policy: 'full_retention_context_distillation',
    policy: {},
    roots: {},
  })
  const fameTimeseries = readJsonl(join(runtimeRoot, 'fame_timeseries.jsonl'))
  const physicalFeedback = readJsonl(join(runtimeRoot, 'physical_feedback_events.jsonl'))
  const routePosterior = readJson(join(runtimeRoot, 'route_posterior_state.json'), {
    state_id: 'empty',
    project_id: manifest.project_id,
    task_id: '',
    goal_gate_id: '',
    entropy: 0,
    selected_route_id: '',
    candidates: [],
  })
  const fullMemoryRetention = readJsonl(join(runtimeRoot, 'full_memory_retention.jsonl'))
  const temporalTruth = readJsonl(join(runtimeRoot, 'temporal_truth_edges.jsonl'))
  const syncOutbox = readJsonl(join(runtimeRoot, 'sync_outbox_events.jsonl'))
  const traceSpans = readJsonl(join(runtimeRoot, 'trace_spans.jsonl'))
  const scacContractionRate =
    physicalFeedback.length === 0
      ? 0
      : physicalFeedback.filter((event) => Number(event.kappa_scac ?? 0) < 1).length / physicalFeedback.length
  const posteriorEntropyDropAvg =
    physicalFeedback.length === 0
      ? 0
      : physicalFeedback.reduce(
          (sum, event) => sum + Number(event.posterior_entropy_before ?? 0) - Number(event.posterior_entropy_after ?? 0),
          0,
        ) / physicalFeedback.length
  const outboxPendingCount = syncOutbox.filter((event) => !['applied', 'replayed'].includes(event.status)).length
  return {
    manifest,
    fameTimeseries,
    physicalFeedback,
    routePosterior,
    fullMemoryRetention,
    temporalTruth,
    syncOutbox,
    traceSpans,
    stats: {
      fame_timeseries_count: fameTimeseries.length,
      physical_feedback_count: physicalFeedback.length,
      route_candidate_count: routePosterior.candidates.length,
      full_memory_retention_count: fullMemoryRetention.length,
      temporal_truth_count: temporalTruth.length,
      sync_outbox_count: syncOutbox.length,
      sync_outbox_pending_count: outboxPendingCount,
      trace_span_count: traceSpans.length,
      scac_contraction_rate: Number(scacContractionRate.toFixed(3)),
      posterior_entropy_drop_avg: Number(posteriorEntropyDropAvg.toFixed(3)),
      generated_at: new Date().toISOString(),
    },
  }
}

function emitTs() {
  return `// Generated by scripts/build-v13-runtime.mjs. Do not edit by hand.
import type {
  FameTimeseriesPoint,
  FullMemoryRetentionState,
  PhysicalFeedbackEvent,
  RoutePosteriorState,
  SyncOutboxEvent,
  TemporalTruthEdge,
  TraceSpanEvent,
} from '../model'

export type V13RuntimeManifest = {
  runtime_id: string
  version: string
  project_id: string
  memory_policy: string
  policy: Record<string, unknown>
  roots: Record<string, string>
  updated_at?: string
}

export type V13RuntimePayload = {
  manifest: V13RuntimeManifest
  fameTimeseries: FameTimeseriesPoint[]
  physicalFeedback: PhysicalFeedbackEvent[]
  routePosterior: RoutePosteriorState
  fullMemoryRetention: FullMemoryRetentionState[]
  temporalTruth: TemporalTruthEdge[]
  syncOutbox: SyncOutboxEvent[]
  traceSpans: TraceSpanEvent[]
  stats: {
    fame_timeseries_count: number
    physical_feedback_count: number
    route_candidate_count: number
    full_memory_retention_count: number
    temporal_truth_count: number
    sync_outbox_count: number
    sync_outbox_pending_count: number
    trace_span_count: number
    scac_contraction_rate: number
    posterior_entropy_drop_avg: number
    generated_at: string
  }
}

const v13RuntimeUrl = \`\${import.meta.env.BASE_URL}generated/v13Runtime.generated.json\`

let cachedV13Runtime: Promise<V13RuntimePayload> | null = null

export function loadV13Runtime() {
  cachedV13Runtime ??= fetch(v13RuntimeUrl).then((response) => {
    if (!response.ok) throw new Error(\`Failed to load v13 runtime: \${response.status} \${response.statusText}\`)
    return response.json() as Promise<V13RuntimePayload>
  })
  return cachedV13Runtime
}
`
}

const payload = buildPayload()
mkdirSync(outDir, { recursive: true })
mkdirSync(publicGeneratedDir, { recursive: true })
writeFileSync(tsOutFile, emitTs(), 'utf8')
writeFileSync(jsonOutFile, JSON.stringify(payload, null, 2), 'utf8')
console.log(
  `Generated ${relative(process.cwd(), tsOutFile)} and ${relative(process.cwd(), jsonOutFile)} with ${payload.stats.fame_timeseries_count} FAME points, ${payload.stats.physical_feedback_count} feedback events, ${payload.stats.full_memory_retention_count} retained memories.`,
)
